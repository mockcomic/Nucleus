'use strict';
/* Windows Core Audio control: enumerate endpoints, switch the default input /
   output device, read and write master volume/mute, and drive the per-app
   mixer (every audio session gets a volume + mute, Windows-Volume-Mixer
   style). All of it runs on documented MMDevice-API interfaces; the default
   device switch uses the de-facto-standard IPolicyConfig (undocumented but
   stable since Windows 7 — every audio switcher in the wild uses it, the
   Windows Settings app included).

   FFI posture (see .dsh/skills/win32-koffi): koffi is loaded ONLY in macro.js;
   this module declares its ole32 symbols through macro.ffi.declareOle32 and
   decodes COM vtable slots through the guarded proto/pointer/decode
   passthroughs. Non-Windows, ia32, a broken koffi install, or a failed
   declaration all fold into the same fail-CLOSED error channel: every public
   function answers { ok: false, error: '<human>' } — never a throw to the
   caller of an IPC handler, and never a crash at require-time.

   Interface layouts (vtable slots after IUnknown 0–2) were verified against
   the autogenerated MinGW-w64 headers (mmdeviceapi / endpointvolume /
   audiopolicy / propsys), i.e. the IDL method order, and against the published
   IPolicyConfig definition (David Kaplan, MSDN "programmatically set the
   default audio endpoint"). */
const macro = require('./macro');

const IS_WIN = process.platform === 'win32';

