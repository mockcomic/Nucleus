/* ---------------- pure helpers (unit-tested; no FFI) ---------------------- */

/** Canonical GUID string → 16-byte COM-layout Buffer (little-endian on the
 *  first three fields, the Data4 octets kept in byte order). Throws on a
 *  malformed literal — every caller passes a constant, so a bad literal must
 *  never reach memory as garbage bytes. */
function guidBytes(hex) {
  const m = /^([0-9a-fA-F]{8})-([0-9a-fA-F]{4})-([0-9a-fA-F]{4})-([0-9a-fA-F]{2})([0-9a-fA-F]{2})-([0-9a-fA-F]{12})$/.exec(String(hex));
  if (!m) throw new Error(`bad GUID literal: ${hex}`);
  const b = Buffer.alloc(16);
  b.writeUInt32LE(parseInt(m[1], 16), 0);
  b.writeUInt16LE(parseInt(m[2], 16), 4);
  b.writeUInt16LE(parseInt(m[3], 16), 6);
  b[8] = parseInt(m[4], 16); b[9] = parseInt(m[5], 16);
  Buffer.from(m[6], 'hex').copy(b, 10);
  return b;
}

/** Accept both UI-facing names and the header names. Returns the EDataFlow
 *  int, or null for anything else (callers must reject null — never guess). */
function parseFlow(f) {
  const k = String(f == null ? '' : f).trim().toLowerCase();
  if (k === 'render' || k === 'output') return E_RENDER;
  if (k === 'capture' || k === 'input') return E_CAPTURE;
  return null;
}

const clampPercent = (v) =>
  (typeof v === 'number' && isFinite(v)) ? Math.min(100, Math.max(0, Math.round(v))) : null;
const percentToScalar = (p) => clampPercent(p) / 100;
const scalarToPercent = (s) => Math.round(Math.min(1, Math.max(0, Number(s) || 0)) * 100);

/** Endpoint ids reach COM as LPCWSTR, so they are held to what Core Audio
 *  itself ever produces: printable ASCII, no control characters, capped at
 *  the config layer's own 2048-field length. Returns '' for a rejection. */
function sanitizeDeviceId(id) {
  const s = String(id == null ? '' : id).trim();
  if (!s || s.length > 512 || !/^[\x20-\x7e]+$/.test(s)) return '';
  return s;
}

/** A device whose FriendlyName came back empty still needs a label: trim the
 *  endpoint-id tail so the row stays identifiable instead of blank. */
function fallbackName(id) {
  const s = String(id || '');
  const tail = s.includes('::') ? s.slice(s.lastIndexOf('::') + 2) : s;
  const t = tail.replace(/[{}]/g, '');
  return (t || s).slice(0, 60);
}

/** Group raw session rows (one per stream) into mixer rows (one per process),
 *  Windows-Volume-Mixer semantics: the system-sounds session keeps its own
 *  row; processes fold their streams into the row of their first stream.
 *  Pure — `rows` is [{pid, title, exe, isSystem, volume, muted, sessions}]. */
function groupSessions(rows) {
  const out = [];
  const byPid = new Map();
  for (const r of rows || []) {
    if (!r || !Number.isFinite(r.pid)) continue;
    if (r.isSystem) { out.push(Object.assign({}, r)); continue; }
    if (r.pid === 0) continue;                       // no owner process — nothing to control
    const g = byPid.get(r.pid);
    if (!g) byPid.set(r.pid, Object.assign({}, r, { sessions: 1 }));
    else {
      g.sessions += 1;
      // Label preference across a process's streams: any named stream wins.
      if (!g.title && r.title) g.title = r.title;
      // A stream the user unmuted keeps the row audible-looking.
      g.muted = g.muted && r.muted;
    }
  }
  out.push(...byPid.values());
  // Deterministic, mixer-like order: audible rows first, then by label.
  out.sort((a, b) => (a.isSystem ? 1 : 0) - (b.isSystem ? 1 : 0)
    || String(a.title || a.exe || '?').localeCompare(String(b.title || b.exe || '?')));
  return out;
}

/* ---------------- COM plumbing (guarded, lazy) ----------------------------- */

let _api = null, _apiErr = null, _comInit = 0;   // _comInit: 0 unknown, 1 ok, -1 failed

/* One lazy declaration pass: the ole32 entry points every call below needs.
   Returns null with _apiErr set when the stack cannot run at all. */
function com() {
  if (_api) return _api;
  if (_apiErr) return null;
  if (!IS_WIN) { _apiErr = 'audio control is only available on Windows'; return null; }
  if (!macro.ffi.available) { _apiErr = macro.ffi.loadError || 'input bridge unavailable'; return null; }
  if (!macro.ffi.comAvailable) { _apiErr = macro.ffi.comLoadError || 'ole32 unavailable'; return null; }
  try {
    _api = {
      CoInitializeEx: macro.ffi.declareOle32('int32 __stdcall CoInitializeEx(void* pvReserved, uint32 dwCoInit)'),
      CoCreateInstance: macro.ffi.declareOle32('int32 __stdcall CoCreateInstance(void* rclsid, void* pUnkOuter, uint32 dwClsCtx, void* riid, void* ppvOut)'),
      CoTaskMemFree: macro.ffi.declareOle32('void __stdcall CoTaskMemFree(void* pv)'),
      PropVariantClear: macro.ffi.declareOle32('int32 __stdcall PropVariantClear(void* pvar)')
    };
  } catch (e) {
    _api = null;
    _apiErr = String((e && e.message) || e);
    return null;
  }
  // COM must be initialized on THIS thread before any CoCreateInstance. The
  // main process may already have done it (Electron does, either model):
  // S_OK (we own it), S_FALSE / RPC_E_CHANGED_MODE (someone else did) are all
  // usable; a hard failure takes the whole feature down, cleanly.
  try {
    const hr = _api.CoInitializeEx(null, 0 /* COINIT_MULTITHREADED */);
    _comInit = (hr === 0 || hr === 1 || hr === -2147417850 /* RPC_E_CHANGED_MODE */) ? 1 : -1;
  } catch (e) {
    _comInit = -1;
    _apiErr = String((e && e.message) || e);
    _api = null;
    return null;
  }
  if (_comInit !== 1) { _api = null; _apiErr = 'COM could not be initialized'; return null; }
  return _api;
}

/** Why the feature cannot run (null = it can). */
function unavailable() {
  com();
  return _apiErr;
}

/* Decode a vtable slot into a callable. The proto per method name is built
   once (repeated poll calls stay cheap); the vtable walk happens per call
   because every interface pointer has its own vtable. koffi's
   decode(ptr, protoType) hands back a real JS function (see
   node_modules/koffi/doc/functions.md). */
const _protoCache = new Map();
function methodProto(key, argTypes) {
  let proto = _protoCache.get(key);
  if (!proto) {
    proto = macro.ffi.proto(`int32 __stdcall ${key}(${['void*', ...argTypes].join(', ')})`);
    _protoCache.set(key, proto);
  }
  return proto;
}
function vcall(iface, slot, key, argTypes) {
  const proto = methodProto(key, argTypes);
  const vtbl = macro.ffi.decode(iface, 0, 'void*');
  const fnPtr = macro.ffi.decode(vtbl, slot * 8, 'void*');
  return macro.ffi.decodeType(fnPtr, proto);   // 2-arg decode: the function-pointer form
}

const S_OK = 0;
function ok(hr_) { return (hr_ | 0) === 0; }
function fail(hr_, what) {
  const err = new Error(`${what} failed (0x${(hr_ >>> 0).toString(16).padStart(8, '0')})`);
  err.hresult = hr_ >>> 0;
  return err;
}

function coCreate(clsid, iid) {
  const out = Buffer.alloc(8);
  const h = com().CoCreateInstance(guidBytes(clsid), null, CLSCTX_INPROC_SERVER, guidBytes(iid), out);
  if (!ok(h)) throw fail(h, `CoCreateInstance(${clsid})`);
  return macro.ffi.decode(out, 0, 'void*');
}

function release(iface) {
  if (!iface) return;
  try { vcall(iface, S.Release, 'IUnknown_Release', []) (iface); } catch { /* best effort */ }
}

function query(iface, iid, key) {
  const out = Buffer.alloc(8);
  const h = vcall(iface, S.QI, key + '_QI', ['void*', 'void**'])(iface, guidBytes(iid), out);
  if (!ok(h)) throw fail(h, 'QueryInterface');
  return macro.ffi.decode(out, 0, 'void*');
}

function createEnumerator() {
  return coCreate(CLSID_MMDeviceEnumerator, IID_IMMDeviceEnumerator);
}

function defaultDevice(en, flow) {
  const out = Buffer.alloc(8);
  const h = vcall(en, S.enum_Default, 'IMMDeviceEnumerator_GetDefault', ['int32', 'int32', 'void**'])(en, flow, E_CONSOLE, out);
  if (!ok(h)) throw fail(h, 'GetDefaultAudioEndpoint');
  return macro.ffi.decode(out, 0, 'void*');
}

function deviceId(dev) {
  const out = Buffer.alloc(8);
  const h = vcall(dev, S.dev_GetId, 'IMMDevice_GetId', ['void**'])(dev, out);
  if (!ok(h)) throw fail(h, 'GetId');
  // String reads decode from the raw out-Buffer (decode(buf, off, 'str16')):
  // koffi cannot decode a string type from a decoded External pointer.
  const s = macro.ffi.decode(out, 0, 'str16') || '';
  try { com().CoTaskMemFree(macro.ffi.decode(out, 0, 'void*')); } catch { /* best effort */ }
  return s;
}

function deviceName(dev, id) {
  const out = Buffer.alloc(8);
  let store = null;
  try {
    const h = vcall(dev, S.dev_OpenPropertyStore, 'IMMDevice_OpenPropertyStore', ['uint32', 'void**'])(dev, STGM_READ, out);
    if (!ok(h)) return fallbackName(id);
    store = macro.ffi.decode(out, 0, 'void*');
    // PROPERTYKEY = GUID fmtid + u32 pid.
    const key = Buffer.alloc(20);
    guidBytes(FMTID_DEVPROP).copy(key, 0);
    key.writeUInt32LE(PID_FRIENDLY_NAME, 16);
    const pv = Buffer.alloc(32);                      // zeroed PROPVARIANT (x64 needs 16, 32 = margin)
    const hv = vcall(store, S.store_GetValue, 'IPropertyStore_GetValue', ['void*', 'void**'])(store, key, pv);
    try {
      if (!ok(hv)) return fallbackName(id);
      // x64 PROPVARIANT: vt u16 @0, union @8 — VT_LPWSTR keeps the pointer there.
      if (pv.readUInt16LE(0) !== VT_LPWSTR) return fallbackName(id);
      return macro.ffi.decode(pv, 8, 'str16').trim() || fallbackName(id);
    } finally {
      try { com().PropVariantClear(pv); } catch { /* best effort */ }
    }
  } catch {
    return fallbackName(id);
  } finally {
    release(store);
  }
}

function activate(dev, iid, key) {
  const out = Buffer.alloc(8);
  const h = vcall(dev, S.dev_Activate, 'IMMDevice_Activate', ['void*', 'uint32', 'void*', 'void**'])(dev, guidBytes(iid), CLSCTX_INPROC_SERVER, null, out);
  if (!ok(h)) throw fail(h, `Activate(${iid})`);
  return macro.ffi.decode(out, 0, 'void*');
}

/* ---------------- public API ------------------------------------------------
   Every function is synchronous (COM marshals on this thread; an endpoint
   enumeration is single-digit milliseconds) and answers {ok:true,…} or
   {ok:false,error}. ipc.js registers them read-only or Settings-gated. */

/** {ok, devices:[{id, name, isDefault}]} for one direction of the world. */
function listDevices(flowName) {
  const flow = parseFlow(flowName);
  if (flow === null) return { ok: false, error: 'flow must be render or capture' };
  if (unavailable()) return { ok: false, error: unavailable() };
  let en = null, coll = null, dev = null;
  try {
    en = createEnumerator();
    let defId = '';
    try {
      dev = defaultDevice(en, flow);
      defId = deviceId(dev);
    } catch { defId = ''; }                            // no default yet is a state, not an error
    release(dev); dev = null;

    const co = Buffer.alloc(8);
    const h = vcall(en, S.enum_Endpoint, 'IMMDeviceEnumerator_Enum', ['int32', 'uint32', 'void**'])(en, flow, DEVICE_STATE_ACTIVE, co);
    if (!ok(h)) throw fail(h, 'EnumAudioEndpoints');
    coll = macro.ffi.decode(co, 0, 'void*');

    const nOut = Buffer.alloc(4);
    const hc = vcall(coll, S.coll_Count, 'IMMDeviceCollection_GetCount', ['uint32*'])(coll, nOut);
    if (!ok(hc)) throw fail(hc, 'GetCount');
    const n = nOut.readUInt32LE(0);

    const devices = [];
    for (let i = 0; i < n; i++) {
      const io = Buffer.alloc(8);
      const hi = vcall(coll, S.coll_Item, 'IMMDeviceCollection_Item', ['uint32', 'void**'])(coll, i, io);
      if (!ok(hi)) continue;                            // one flaky entry must not sink the list
      dev = macro.ffi.decode(io, 0, 'void*');
      try {
        const id = deviceId(dev);
        if (!id) continue;
        devices.push({ id, name: deviceName(dev, id), isDefault: id === defId });
      } finally {
        release(dev); dev = null;
      }
    }
    return { ok: true, devices };
  } catch (e) {
    return { ok: false, error: String((e && e.message) || e) };
  } finally {
    release(dev); release(coll); release(en);
  }
}

/** Flip the system default for one direction (IPolicyConfig, then verified
 *  by reading the default back through the documented enumerator). */
function setDefaultDevice(flowName, deviceIdRaw) {
  const flow = parseFlow(flowName);
  if (flow === null) return { ok: false, error: 'flow must be render or capture' };
  const id = sanitizeDeviceId(deviceIdRaw);
  if (!id) return { ok: false, error: 'that audio device id is not usable' };
  if (unavailable()) return { ok: false, error: unavailable() };
  let pc = null;
  try {
    try {
      pc = coCreate(CLSID_PolicyConfigClient, IID_IPolicyConfig);
    } catch (e) {
      // Older builds only know the legacy coclass. If BOTH are unknown to COM
      // (REGDB_E_CLASSNOTREG = 0x80040154, no InprocServer32 anywhere), the
      // Windows image is missing the private audio-policy registration —
      // no user-mode app can set defaults on it, so say exactly that.
      if (e && e.hresult === 0x80040154) {
        pc = coCreate(CLSID_PolicyConfig, IID_IPolicyConfig);
      } else throw e;
    }
    let h = vcall(pc, S.policy_SetDefault, 'IPolicyConfig_SetDefaultEndpoint', ['str16', 'int32'])(pc, id, flow);
    if (!ok(h)) {
      release(pc); pc = null;
      pc = coCreate(CLSID_PolicyConfig, IID_IPolicyConfig);
      h = vcall(pc, S.policy_SetDefault, 'IPolicyConfig_SetDefaultEndpoint', ['str16', 'int32'])(pc, id, flow);
      if (!ok(h)) throw fail(h, 'SetDefaultEndpoint');
    }
    release(pc); pc = null;
    // Read-back through the documented path: the switch must be observable
    // before we claim it worked.
    const en = createEnumerator();
    try {
      const dev = defaultDevice(en, flow);
      try {
        if (deviceId(dev) !== id) return { ok: false, error: 'Windows refused the switch (the device may be busy or already gone)' };
      } finally { release(dev); }
    } finally { release(en); }
    return { ok: true };
  } catch (e) {
    // REGDB_E_CLASSNOTREG on both coclasses = the OS image lacks the private
    // audio-policy registration (custom/stripped installs). No user-mode app
    // can set defaults then — tell the user what it actually means.
    if (e && e.hresult === 0x80040154) {
      return { ok: false, error: 'this Windows install is missing its audio-policy component, so no app can change the default device — use Windows sound settings (below)' };
    }
    return { ok: false, error: String((e && e.message) || e) };
  } finally {
    release(pc);
  }
}

/** Activate IAudioEndpointVolume on this flow's default endpoint and run fn
 *  against it, releasing everything afterwards. */
function withEndpointVolume(flow, fn) {
  const en = createEnumerator();
  let dev = null, vol = null;
  try {
    dev = defaultDevice(en, flow);
    vol = activate(dev, IID_IAudioEndpointVolume, 'IAudioEndpointVolume');
    return fn(vol);
  } finally {
    release(vol); release(dev); release(en);
  }
}

/** {ok, volume, muted} for the default endpoint of one direction. */
function getLevels(flowName) {
  const flow = parseFlow(flowName);
  if (flow === null) return { ok: false, error: 'flow must be render or capture' };
  if (unavailable()) return { ok: false, error: unavailable() };
  try {
    return withEndpointVolume(flow, (vol) => {
      const vOut = Buffer.alloc(4);
      const hv = vcall(vol, S.vol_GetMasterScalar, 'IAudioEndpointVolume_GetScalar', ['float*'])(vol, vOut);
      if (!ok(hv)) throw fail(hv, 'GetMasterVolumeLevelScalar');
      const mOut = Buffer.alloc(4);
      const hm = vcall(vol, S.vol_GetMute, 'IAudioEndpointVolume_GetMute', ['int32*'])(vol, mOut);
      if (!ok(hm)) throw fail(hm, 'GetMute');
      return { ok: true, volume: scalarToPercent(vOut.readFloatLE(0)), muted: mOut.readUInt32LE(0) !== 0 };
    });
  } catch (e) {
    return { ok: false, error: String((e && e.message) || e) };
  }
}

/** {volume 0–100, muted} — either may be null (= leave unchanged). */
function setLevels(flowName, { volume = null, muted = null } = {}) {
  const flow = parseFlow(flowName);
  if (flow === null) return { ok: false, error: 'flow must be render or capture' };
  if (volume === null && muted === null) return { ok: false, error: 'nothing to change' };
  const pct = volume === null ? null : clampPercent(volume);
  if (volume !== null && pct === null) return { ok: false, error: 'volume must be a number 0–100' };
  if (unavailable()) return { ok: false, error: unavailable() };
  try {
    return withEndpointVolume(flow, (vol) => {
      if (pct !== null) {
        const h = vcall(vol, S.vol_SetMasterScalar, 'IAudioEndpointVolume_SetScalar', ['float', 'void*'])(vol, percentToScalar(pct), null);
        if (!ok(h)) throw fail(h, 'SetMasterVolumeLevelScalar');
      }
      if (muted !== null) {
        const h = vcall(vol, S.vol_SetMute, 'IAudioEndpointVolume_SetMute', ['int32', 'void*'])(vol, muted ? 1 : 0, null);
        if (!ok(h)) throw fail(h, 'SetMute');
      }
      return { ok: true };
    });
  } catch (e) {
    return { ok: false, error: String((e && e.message) || e) };
  }
}

/* Walk every audio session on the default render endpoint, invoking fn(ctrl2)
   per session. The enumerator hands out IAudioSessionControl; the underlying
   object also implements IAudioSessionControl2, so one QI upgrades it (and
   ISimpleAudioVolume is QI'd again from there — no slot-number shortcuts). */
function forEachSession(fn) {
  const en = createEnumerator();
  let dev = null, mgr = null, senum = null;
  try {
    dev = defaultDevice(en, E_RENDER);
    mgr = activate(dev, IID_IAudioSessionManager2, 'IAudioSessionManager2');
    const eo = Buffer.alloc(8);
    const he = vcall(mgr, S.sess2_GetEnumerator, 'IAudioSessionManager2_GetEnumerator', ['void**'])(mgr, eo);
    if (!ok(he)) throw fail(he, 'GetSessionEnumerator');
    senum = macro.ffi.decode(eo, 0, 'void*');

    const cOut = Buffer.alloc(4);
    const hc = vcall(senum, S.senum_Count, 'IAudioSessionEnumerator_GetCount', ['int32*'])(senum, cOut);
    if (!ok(hc)) throw fail(hc, 'session GetCount');
    const n = cOut.readInt32LE(0);

    const results = [];
    for (let i = 0; i < n; i++) {
      const so = Buffer.alloc(8);
      const hs = vcall(senum, S.senum_GetSession, 'IAudioSessionEnumerator_GetSession', ['int32', 'void**'])(senum, i, so);
      if (!ok(hs)) continue;
      const sc = macro.ffi.decode(so, 0, 'void*');
      let c2 = null;
      try {
        c2 = query(sc, IID_IAudioSessionControl2, 'IAudioSessionControl2');
        results.push(fn(c2));
      } finally {
        release(c2); release(sc);
      }
    }
    return results;
  } finally {
    release(senum); release(mgr); release(dev); release(en);
  }
}

function sessionString(c2, slot, key) {
  const out = Buffer.alloc(8);
  const h = vcall(c2, slot, key, ['void**'])(c2, out);
  if (!ok(h)) return '';
  const s = macro.ffi.decode(out, 0, 'str16') || '';
  try { com().CoTaskMemFree(macro.ffi.decode(out, 0, 'void*')); } catch { /* best effort */ }
  return s;
}

function simpleVolume(c2) {
  return query(c2, IID_ISimpleAudioVolume, 'ISimpleAudioVolume');
}

/** Raw session rows (one per stream), mixer-ready. */
function readSessionRows() {
  return forEachSession((c2) => {
    const pidOut = Buffer.alloc(4);
    const hp = vcall(c2, S.sc2_GetProcessId, 'IAudioSessionControl2_GetProcessId', ['uint32*'])(c2, pidOut);
    const pid = ok(hp) ? pidOut.readUInt32LE(0) : 0;
    let isSystem = false;
    try { isSystem = vcall(c2, S.sc2_IsSystemSounds, 'IAudioSessionControl2_IsSystemSounds', [])(c2) === S_OK; } catch { /* keep false */ }
    const title = sessionString(c2, S.sc2_GetDisplayName, 'IAudioSessionControl2_GetDisplayName').trim();
    const exe = pid ? (macro.readExeBase(pid) || '') : '';
    let volume = 0, muted = false;
    let sav = null;
    try {
      sav = simpleVolume(c2);
      const vOut = Buffer.alloc(4);
      if (ok(vcall(sav, S.sav_GetMasterVolume, 'ISimpleAudioVolume_GetMasterVolume', ['float*'])(sav, vOut))) {
        volume = scalarToPercent(vOut.readFloatLE(0));
      }
      const mOut = Buffer.alloc(4);
      if (ok(vcall(sav, S.sav_GetMute, 'ISimpleAudioVolume_GetMute', ['int32*'])(sav, mOut))) {
        muted = mOut.readUInt32LE(0) !== 0;
      }
    } catch { /* an unreadable stream keeps its zero row rather than sinking the list */ }
    finally { release(sav); }
    return { pid, title, exe, isSystem, volume, muted };
  });
}

/** {ok, sessions:[{pid, label, exe, volume, muted, isSystem, sessions}]} — the
 *  per-app mixer rows for the default output device. */
function listSessions() {
  if (unavailable()) return { ok: false, error: unavailable() };
  try {
    const rows = readSessionRows().filter(Boolean);
    const grouped = groupSessions(rows).map((r) => ({
      pid: r.pid,
      isSystem: !!r.isSystem,
      exe: r.exe || '',
      label: (r.isSystem ? 'System sounds' : (r.title || r.exe || `audio session ${r.pid}`)),
      volume: r.volume,
      muted: !!r.muted,
      sessions: r.sessions || 1
    }));
    return { ok: true, sessions: grouped };
  } catch (e) {
    return { ok: false, error: String((e && e.message) || e) };
  }
}

/** Apply {volume?, muted?} to EVERY stream of one process (mixer semantics).
 *  A pid that vanished between list and set is a clean error, not a no-op. */
function setSession(pid, { volume = null, muted = null } = {}) {
  const p = Number(pid);
  if (!Number.isInteger(p) || p <= 0) return { ok: false, error: 'a real process id is required' };
  if (volume === null && muted === null) return { ok: false, error: 'nothing to change' };
  const pct = volume === null ? null : clampPercent(volume);
  if (volume !== null && pct === null) return { ok: false, error: 'volume must be a number 0–100' };
  if (unavailable()) return { ok: false, error: unavailable() };
  let touched = 0, firstErr = null;
  try {
    forEachSession((c2) => {
      const pidOut = Buffer.alloc(4);
      const hp = vcall(c2, S.sc2_GetProcessId, 'IAudioSessionControl2_GetProcessId', ['uint32*'])(c2, pidOut);
      if (!ok(hp) || pidOut.readUInt32LE(0) !== p) return null;
      let sav = null;
      try {
        sav = simpleVolume(c2);
        if (pct !== null) {
          const h = vcall(sav, S.sav_SetMasterVolume, 'ISimpleAudioVolume_SetMasterVolume', ['float', 'void*'])(sav, percentToScalar(pct), null);
          if (!ok(h)) { firstErr = firstErr || fail(h, 'SetMasterVolume'); return null; }
        }
        if (muted !== null) {
          const h = vcall(sav, S.sav_SetMute, 'ISimpleAudioVolume_SetMute', ['int32', 'void*'])(sav, muted ? 1 : 0, null);
          if (!ok(h)) { firstErr = firstErr || fail(h, 'SetMute'); return null; }
        }
        touched += 1;
      } catch (e) {
        firstErr = firstErr || e;
      } finally {
        release(sav);
      }
      return null;
    });
    if (!touched) {
      return firstErr
        ? { ok: false, error: String((firstErr && firstErr.message) || firstErr) }
        : { ok: false, error: 'that app stopped playing audio — refresh the list' };
    }
    return { ok: true };
  } catch (e) {
    return { ok: false, error: String((e && e.message) || e) };
  }
}

/** Static gate for the UI: {ok:true} or {ok:false, reason}. Cheap enough to
 *  call on every tab open. */
function available() {
  const why = unavailable();
  return why ? { ok: false, reason: why } : { ok: true };
}

