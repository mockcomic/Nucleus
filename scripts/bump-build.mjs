/* Increments the electron-builder build number before each dist run: node scripts/bump-build.mjs
   build.buildNumber in package.json (a string, per the electron-builder schema) is consumed
   natively: Windows exe FileVersion becomes `<version>.<build>`, the NSIS installer takes the
   same VIProductVersion, and artifact names expand the ${buildNumber} macro. The seed "0"
   means "never packaged"; the first dist run after that lands on 1. */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

/** '7' → '8'; undefined / '' / garbage is treated as unseeded → '1'. Pure — unit-tested. */
export function nextBuildNumber(current) {
  const s = typeof current === 'string' || typeof current === 'number' ? String(current) : '';
  const n = /^\d+$/.test(s) ? parseInt(s, 10) : 0;
  return String(n + 1);
}

/* CLI mode only — importing this module (tests) must never touch files. */
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const root = path.resolve(import.meta.dirname, '..');
  const pkgPath = path.join(root, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  const cfg = (pkg.build ??= {});
  cfg.buildNumber = nextBuildNumber(cfg.buildNumber);
  // Round-trip keeps key order and the repo's 2-space style; a throw here exits
  // non-zero so the dist chain halts before electron-builder starts.
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  // electron-builder strips the `build` block from the packaged package.json,
  // so the app's own version surfaces (log banner, welcome) read the number
  // from this generated module instead — it rides the src/**/* files whitelist,
  // committed like the other generated artifact (assets/tray.ico).
  const infoPath = path.join(root, 'src', 'main', 'build-info.js');
  fs.writeFileSync(infoPath,
    '/* generated by scripts/bump-build.mjs — do not edit; regenerated on every npm run dist */\n' +
    `'use strict';\nmodule.exports = { buildNumber: '${cfg.buildNumber}' };\n`);
  console.log(`build number → ${cfg.buildNumber}`);
}
